"""Generate docs/METRICS.md from the metric registry (single source of truth)."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from collections import Counter
from cfbquant.analytics import player_metrics as pm, team_metrics as tm

out = ["# Metric Registry", "", "Generated by `scripts/gen_metrics_doc.py` from the code registry. Do not edit by hand.", "",
       "Classification: **observed** (counted from source), **calculated** (deterministic formula), **estimated** (model / proxy), "
       "**unavailable_without_charting** (requires licensed charting/tracking/participation data; never filled with fabricated values).", ""]
t = tm.ALL_TEAM_METRICS
out += [f"## Team metrics ({len(t)})", "", "| Category | Count | Computable | Charting-only |", "|---|---|---|---|"]
for c in tm.CATS:
    ms = [m for m in t if m.cat == c]
    u = sum(m.classification == "unavailable_without_charting" for m in ms)
    out.append(f"| {c} | {len(ms)} | {len(ms) - u} | {u} |")
for c in tm.CATS:
    out += ["", f"### {c}", "", "| id | name | side | dir | class | opp-adj | formula |", "|---|---|---|---|---|---|---|"]
    for m in [m for m in t if m.cat == c]:
        out.append(f"| `{m.mid}` | {m.name} | {m.side} | {m.direction:+d} | {m.classification} | {'yes' if m.adj else ''} | {m.formula.replace('|', '/')} |")
u = [d for d in pm.DEFS if d.scope == "player_universal"]
p = [d for d in pm.DEFS if d.scope == "player_position"]
cnt = Counter(d.classification for d in pm.DEFS)
out += ["", f"## Player metrics ({len(pm.DEFS)}: {len(u)} universal, {len(p)} position-specific)", "",
        ", ".join(f"{k}: {v}" for k, v in cnt.items()), ""]
for title, lst in (("Universal", u), ("Position-specific", p)):
    out += [f"### {title}", "", "| id | category | name | positions | dir | class | formula |", "|---|---|---|---|---|---|---|"]
    for d in lst:
        out.append(f"| `{d.mid}` | {d.cat} | {d.name} | {d.positions} | {d.direction:+d} | {d.classification} | {d.formula.replace('|', '/')} |")
Path("docs/METRICS.md").write_text("\n".join(out) + "\n")
print(len(out), "lines")
